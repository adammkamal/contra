import { windowCloses } from "./clock.ts";
import { backChargeAmount } from "./credits.ts";
import { formatUsd, sum } from "./money.ts";
import type { BackCharge, Credit, Job, Notice, Subcontract } from "./types.ts";

/**
 * Delivers a credit memo (e.g. by email to an AP inbox). Injected into App like the Clock; src/ holds
 * no network code, so the implementation lives outside it (server/gmail.ts). send() resolves when the
 * memo was accepted for delivery and rejects with an Error whose message is safe to show and to audit.
 */
export interface MemoSender {
  /** Where memos go, as shown on screen and in the audit log (an email address). */
  readonly destination: string;
  send(memo: { creditId: string; filename: string; text: string }): Promise<{ messageId: string }>;
}

export interface MemoInput {
  credit: Readonly<Credit>;
  subcontract: Readonly<Subcontract>;
  job: Readonly<Job>;
  vendorName: string;
  items: readonly Readonly<BackCharge>[];
  notices: readonly Readonly<Notice>[];
  approvedAt: Date;
}

const day = (d: Date) => d.toISOString().slice(0, 10);

/**
 * The document Contra produces for the production route: forwarded to the GC's Ramp AP inbox,
 * where Ramp drafts a vendor credit and an AP clerk finishes it. Ramp requires a vendor name and
 * line items; each back-charge is one line, coded to the job.
 */
export function renderCreditMemo(m: MemoInput): { filename: string; text: string } {
  if (m.credit.state !== "approved" && m.credit.state !== "synced" && m.credit.state !== "applied") {
    throw new Error(`credit ${m.credit.id} is ${m.credit.state}; memos exist only for approved credits`);
  }
  const refs = new Set(m.credit.backChargeRefs);
  if (m.items.length !== refs.size || !m.items.every((b) => refs.has(b.ref))) {
    throw new Error(`memo items do not match credit ${m.credit.id}`);
  }
  const total = sum(m.items.map(backChargeAmount));
  if (total !== m.credit.amountCents) {
    throw new Error(`memo lines total ${formatUsd(total)} but credit is ${formatUsd(m.credit.amountCents)}`);
  }

  const clause = m.subcontract.clause!;
  const lines = m.items.map(
    (b) => `${b.ref.padEnd(9)} ${b.extracted.description.slice(0, 48).padEnd(48)} ${m.job.id.padEnd(7)} ${formatUsd(backChargeAmount(b)).padStart(12)}`,
  );
  const noticeLines = m.notices.map((n) => {
    const closes = windowCloses(n.sentAt!, clause.responseWindow);
    return `  ${n.id}: sent ${day(n.sentAt!)}, approved by ${n.approvedBy}; response window closed ${day(closes)}`;
  });

  const text = [
    `VENDOR CREDIT MEMO ${m.credit.id}`,
    `Date: ${day(m.approvedAt)}`,
    `Vendor: ${m.vendorName} (Ramp vendor ${m.credit.vendorId})`,
    `Job: ${m.job.id} ${m.job.name}`,
    `Subcontract: ${m.subcontract.id} (${m.subcontract.scope}), ${clause.section}`,
    `Reference bill: none (credit from vendor profile)`,
    ``,
    `${"Ref".padEnd(9)} ${"Description".padEnd(48)} ${"Job".padEnd(7)} ${"Amount".padStart(12)}`,
    ...lines,
    `${"".padEnd(9)} ${"TOTAL CREDIT".padEnd(48)} ${"".padEnd(7)} ${formatUsd(total).padStart(12)}`,
    ``,
    `Basis:`,
    ...noticeLines,
    // An item the PM's email gave no BC number is listed under Contra's reference, said in words.
    ...m.items.filter((b) => b.bcNumber === null).map((b) => `  ${b.ref}: no BC number yet; ${b.ref} is Contra's reference for it.`),
    `  No item on this memo was disputed in the source emails or by the subcontractor.`,
    `Approved by: ${m.credit.approvedBy} on ${day(m.approvedAt)}`,
    ``,
    `Generated by Contra. Forward to the Ramp AP inbox; finish the draft vendor credit in Ramp.`,
  ].join("\n");

  return { filename: `${m.credit.id}-${m.subcontract.id}.txt`, text };
}
